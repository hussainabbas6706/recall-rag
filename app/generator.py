"""Answer generation using Google's Gemini chat model."""

from langchain_core.language_models.chat_models import BaseChatModel
from langchain_google_genai import ChatGoogleGenerativeAI

from app.config import get_settings


def get_chat_model(api_key: str | None = None) -> BaseChatModel:
    """Return an initialized ChatGoogleGenerativeAI instance.

    Raises:
        ValueError: If no Gemini API key is provided or configured.
    """
    settings = get_settings()
    key = api_key if api_key is not None else settings.gemini_api_key
    if not key:
        raise ValueError("GEMINI_API_KEY is not configured. Please set it in your .env file.")

    model_name = settings.answer_model
    return ChatGoogleGenerativeAI(
        model=model_name,
        google_api_key=key,
        temperature=0.0,
    )


def generate_answer(
    prompt: str,
    model: BaseChatModel | None = None,
) -> str:
    """Generate an answer from a pre-built RAG prompt.

    Args:
        prompt: The formatted prompt string from build_rag_prompt().
        model: Optional initialized chat model (useful for testing/mocking).

    Returns:
        The grounded answer string generated by the LLM.

    Raises:
        ValueError: If the prompt is empty or whitespace.
    """
    clean_prompt = prompt.strip()
    if not clean_prompt:
        raise ValueError("Prompt cannot be empty.")

    chat_model = model or get_chat_model()
    response = chat_model.invoke(clean_prompt)

    if isinstance(response.content, str):
        return response.content.strip()
    if isinstance(response.content, list):
        parts: list[str] = []
        for part in response.content:
            if isinstance(part, str):
                parts.append(part)
            elif isinstance(part, dict) and "text" in part:
                parts.append(str(part["text"]))
        return "".join(parts).strip()
    return str(response.content).strip()
